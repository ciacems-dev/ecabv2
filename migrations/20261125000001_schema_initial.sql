-- Schéma initial ECAB-MS, traduit fidèlement du schéma MariaDB d'origine (Doctrine).
-- Mêmes noms de tables et de colonnes, sauf `user` → `users` (mot réservé PostgreSQL).
-- Les colonnes nullable le restent : les règles de gestion existantes distinguent parfois NULL et false.
-- Les dates sans fuseau restent en `timestamp` (Côte d'Ivoire = UTC+0, comme les données existantes).

CREATE TABLE zone (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codezone  varchar(50),
    libzone   varchar(255)
);

CREATE TABLE pays (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id       integer REFERENCES zone (id),
    nompays       varchar(255) NOT NULL,
    tva           varchar(255),
    capital       varchar(255),
    monnaie_code  varchar(50),
    monnaie_nom   varchar(50),
    indicatif     varchar(50),
    iso_code2     varchar(50),
    iso_code3     varchar(50),
    iso_number    varchar(50),
    ltd           varchar(255)
);
CREATE INDEX idx_pays_zone ON pays (zone_id);

-- Services / entités (« destinataires » des imputations)
CREATE TABLE destinataire (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle  varchar(255) NOT NULL,
    statut   boolean
);

CREATE TABLE users (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pays_id          integer REFERENCES pays (id),
    destinataire_id  integer REFERENCES destinataire (id),
    email            varchar(180) NOT NULL UNIQUE,
    roles            jsonb NOT NULL DEFAULT '[]',
    password         varchar(255) NOT NULL,
    is_verified      boolean NOT NULL DEFAULT false,
    nom              varchar(50),
    prenom           varchar(255),
    civilite         varchar(50),
    telephone        varchar(255),
    active           boolean
);
CREATE INDEX idx_users_pays ON users (pays_id);
CREATE INDEX idx_users_destinataire ON users (destinataire_id);

CREATE TABLE loginattemp (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer REFERENCES users (id),
    ip          varchar(255),
    date_start  timestamp,
    date_end    timestamp
);
CREATE INDEX idx_loginattemp_user ON loginattemp (user_id);
CREATE INDEX idx_loginattemp_date_start ON loginattemp (date_start);

-- Courrier arrivé
CREATE TABLE carrive (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire_id  integer REFERENCES destinataire (id),
    datearrive       timestamp,
    numero           integer,
    datecour         date,
    numcour          integer,
    expeditaire      varchar(255),
    objet            text,
    courrier         varchar(255),
    create_at        timestamp NOT NULL,
    date             date,
    archive          boolean,
    confi            boolean,
    deposant         varchar(255),
    action           boolean
);
CREATE INDEX idx_carrive_destinataire ON carrive (destinataire_id);
CREATE INDEX idx_carrive_date ON carrive (date);
CREATE INDEX idx_carrive_numero ON carrive (numero);

CREATE TABLE document (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arrive_id  integer REFERENCES carrive (id),
    libelle    varchar(255),
    createat   timestamp,
    fichier    varchar(255)
);
CREATE INDEX idx_document_arrive ON document (arrive_id);

-- Imputation d'un courrier arrivé à un service
CREATE TABLE imputation (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courrier_id      integer REFERENCES carrive (id),
    destinataire_id  integer REFERENCES destinataire (id),
    responsable_id   integer REFERENCES users (id),
    date             date,
    delais           date,
    reponse          varchar(255),
    statut           boolean,
    commentaire      text,
    etat             text,
    doctoure         varchar(255),
    dateretour       timestamp,
    observationdir   text,
    dateobs          timestamp,
    docfinal         varchar(255),
    datefinale       timestamp,
    effet            varchar(255),
    archive          boolean,
    transmet         boolean
);
CREATE INDEX idx_imputation_courrier ON imputation (courrier_id);
CREATE INDEX idx_imputation_destinataire ON imputation (destinataire_id);
CREATE INDEX idx_imputation_responsable ON imputation (responsable_id);
CREATE INDEX idx_imputation_date ON imputation (date);

CREATE TABLE typedepart (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle  varchar(255) NOT NULL,
    statut   boolean NOT NULL
);

-- Courrier départ
CREATE TABLE csortir (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auteur_id      integer REFERENCES destinataire (id),
    type_id        integer REFERENCES typedepart (id),
    datesortir     timestamp,
    numsortir      integer,
    objet          text,
    destinataire   varchar(255),
    courrier       varchar(255),
    decharge       varchar(255),
    update_at      timestamp,
    agent          varchar(255),
    statut         boolean,
    date           date,
    archive        boolean,
    initiateur_id  integer REFERENCES destinataire (id)
);
CREATE INDEX idx_csortir_auteur ON csortir (auteur_id);
CREATE INDEX idx_csortir_type ON csortir (type_id);
CREATE INDEX idx_csortir_initiateur ON csortir (initiateur_id);
CREATE INDEX idx_csortir_date ON csortir (date);

CREATE TABLE compterendu (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date        date NOT NULL,
    time        varchar(255),
    debut       time,
    fin         time,
    lieu        varchar(255),
    presidence  varchar(255),
    cr          varchar(255),
    listep      varchar(255),
    create_at   timestamp NOT NULL,
    redacteur   varchar(255),
    archive     boolean,
    objet       text,
    statut      boolean
);

CREATE TABLE diligence (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cr_id        integer REFERENCES compterendu (id),
    titre        varchar(255),
    libelle      text,
    ressource    varchar(255),
    delai        date,
    debut        date,
    etat         boolean,
    observation  text,
    create_at    timestamp NOT NULL,
    update_at    date,
    archive      boolean,
    taux         integer
);
CREATE INDEX idx_diligence_cr ON diligence (cr_id);
CREATE INDEX idx_diligence_debut ON diligence (debut);

CREATE TABLE mission (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire_id  integer REFERENCES destinataire (id),
    objet            varchar(255) NOT NULL,
    budget           varchar(255),
    transport        varchar(255),
    destination      varchar(255),
    datedebut        date,
    datefin          date,
    participant      varchar(255),
    matricule        varchar(255),
    emploi           varchar(255),
    fonction         varchar(255),
    ordrem           varchar(255),
    rapportm         varchar(255),
    statutr          boolean,
    lieu             varchar(255),
    numero           integer,
    dateenregistre   date
);
CREATE INDEX idx_mission_destinataire ON mission (destinataire_id);

CREATE TABLE audience (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire_id  integer REFERENCES destinataire (id),
    date             date NOT NULL,
    heure            time,
    nom              varchar(255),
    service          varchar(255),
    telephone        varchar(255),
    rdv              boolean,
    objet            text,
    qualite          text,
    statut           boolean,
    commentaire      text,
    email            varchar(255)
);
CREATE INDEX idx_audience_destinataire ON audience (destinataire_id);

CREATE TABLE rendvous (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audience_id  integer REFERENCES audience (id),
    date         date,
    heured       time,
    heuref       time,
    lieu         varchar(255),
    datefin      date,
    message      text
);
CREATE INDEX idx_rendvous_audience ON rendvous (audience_id);
